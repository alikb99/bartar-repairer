// The repair technicians who actually work on customers' devices, plus the
// people who write the site's articles.
//
// RULE FOR THIS FILE: nothing here is invented. Names, specialties and years
// came from the owner. Every other field is optional and renders only when it
// holds a real value. Do NOT fill specialty, years or certifications with
// plausible-sounding guesses — a team page exists to prove the team is real,
// and a single made-up credential destroys exactly the trust it was meant to
// build.
//
// `bio`, `about`, `does`, `notFor` and `faqs` are the derived fields: they
// restate the owner-supplied `specialty` and `years` in sentences, and may only
// mention equipment that already appears in WORKSHOP_TOOLS below (itself
// owner-verified) and policies that already appear in FAQS in lib/data.ts
// (free diagnosis, six-month warranty, same-day parts work, one to three
// working days for board repair). They must never add a credential, an award,
// a former employer, a branch assignment or a division of labour the owner did
// not state. When the owner supplies his own wording, replace the text here
// with it verbatim.

/** Subject areas a person is the named author for. See lib/authors.ts. */
export type Topic =
  | "mobile" // گوشی — تعمیر سخت افزاری و برد
  | "mobile-parts" // گوشی — تعویض قطعات
  | "laptop" // لپ تاپ و مانیتور
  | "tablet" // تبلت
  | "watch" // ساعت هوشمند
  | "niche-phones" // ناتینگ فون، گوگل پیکسل و نوکیا
  | "software"; // تعمیرات نرم افزاری، آموزش و تنظیمات

export type Person = {
  /** URL segment under /team/. Stable — changing it breaks a live URL. */
  slug: string;
  /** Name as given by the owner. */
  name: string;
  /** How this person is presented on the site. */
  role: "manager" | "technician" | "writer";
  /** What this person actually works on. Owner-supplied only. */
  specialty?: string;
  /** Whole years of experience. Owner-supplied only, never estimated. */
  years?: number;
  /**
   * How precise the years figure is, in the owner's own words:
   *   "approx" → "تقریبا ۵ سال"  → rendered "حدود ۵ سال"
   *   "min"    → "بالای ۱۰ سال"  → rendered "بیش از ۱۰ سال"
   * Omitted when the owner gave a flat number.
   */
  yearsNote?: "approx" | "min";
  /** Profile prose. Derived from specialty + years only — see the file header. */
  bio?: string;
  /**
   * The rest of the profile prose, one paragraph per entry. Same derivation
   * rule as `bio`: it describes how the owner-supplied specialty is carried
   * out, and adds no new claim about the person.
   */
  about?: string[];
  /** Concrete jobs that fall inside the owner-supplied specialty. */
  does?: string[];
  /**
   * When a customer should NOT ask for this person. Required reading in
   * CLAUDE.md: a profile that only sells is worth less than one that says
   * where the person is the wrong choice.
   */
  notFor?: string;
  /** Names from WORKSHOP_TOOLS this person works with. */
  tools?: string[];
  /** Questions customers ask about this person's own work. */
  faqs?: { q: string; a: string }[];
  /** Topics this person is credited as the author for, on every page type. */
  topics?: Topic[];
  /**
   * Topics this person is credited as the author for on ARTICLES ONLY. Writers
   * carry these rather than `topics`: they write the guides but do not repair,
   * so they never take a service page's byline. See lib/authors.ts.
   */
  articleTopics?: Topic[];
  /**
   * Public profiles that corroborate this person's identity. Owner-supplied
   * URLs only — schema.org sameAs is an identity claim, so a guessed profile
   * is worse than no profile. Tracking parameters are stripped.
   */
  profiles?: { linkedin?: string; github?: string; instagram?: string };
  /** Path under /wp-content/uploads/. Added once real photos arrive. */
  photo?: { src: string; w: number; h: number };
  /** Real certifications only. */
  certifications?: string[];
};

