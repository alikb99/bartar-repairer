/**
 * The stable schema.org @id for a person's node, anchored on their own
 * profile page — the same pattern as SITE.organizationId / SITE.authorId in
 * lib/data.ts. Every article credited to this person references this id
 * rather than repeating the Person node, so there is exactly one canonical
 * description of them for search engines to read.
 */
export function personId(domain: string, slug: string): string {
  return `${domain}/team/${slug}/#person`;
}

/** Experience label in the owner's own level of precision. */
export function yearsLabel(t: Person): string | null {
  if (typeof t.years !== "number") return null;
  const n = t.years.toLocaleString("fa-IR");
  if (t.yearsNote === "min") return `بیش از ${n} سال سابقه`;
  if (t.yearsNote === "approx") return `حدود ${n} سال سابقه`;
  return `${n} سال سابقه`;
}

/** Short role label used on cards and profile headers. */
export function roleLabel(p: Person): string {
  if (p.role === "manager") return "سرپرست مجموعه";
  if (p.role === "writer") return "نویسنده و کارشناس محتوا";
  return "تعمیرکار";
}

