/**
 * The colleagues shown at the bottom of a profile: everyone who shares at
 * least one subject area, then the rest of the roster, capped by the caller.
 * Deterministic — it reads PEOPLE in order and never sorts on anything that
 * can change between builds.
 */
export function colleaguesOf(p: Person, limit = 4): Person[] {
  const mine = new Set([...(p.topics ?? []), ...(p.articleTopics ?? [])]);
  const shares = (o: Person) =>
    [...(o.topics ?? []), ...(o.articleTopics ?? [])].some((t) => mine.has(t));
  const others = PEOPLE.filter((o) => o.slug !== p.slug);
  return [...others.filter(shares), ...others.filter((o) => !shares(o))].slice(
    0,
    limit,
  );
}

